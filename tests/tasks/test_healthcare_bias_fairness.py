KIMI_MEMO = """# Memo: Bias audit of a cost-based risk ranking — public synthetic replication

**To:** Clinical Analytics Lead
**Re:** Whether a cost-based algorithmic ranking understates clinical need for Black patients

## Bottom line

In this run of the public synthetic replication bundle, the cost-based ranking
does understate clinical need for Black patients, and the gap is large. All
numbers below are from our own execution of the supplied synthetic-data
workflow (`data_new.csv`, 48,784 patient-years; 32,685 train / 16,099 holdout);
they are **not** the original paper's private-data figures, which I flag
separately at the end.

## What the synthetic replication shows

- **Figure 1b (simulated enrollment threshold at the 97th risk percentile).**
  Under the status-quo cost-based ranking, Black patients make up **18.4%** of
  the flagged population. When the simulation swaps in Black patients below the
  threshold who are sicker (more active chronic conditions) than the marginal
  White patients above it, the Black share rises to **44.8%** — a **2.43x**
  ratio. In other words, there is a substantial pool of Black patients with
  greater measured illness burden sitting just below the cut line the
  cost-based score draws.

- **Table 2 (composition of the top 3% by predicted risk, holdout).** Among
  patients ranked highest by the model trained on total costs, **19.3%** are
  Black; ranked by a model trained on avoidable costs, **25.9%**; ranked by a
  model trained on active chronic conditions (a need-based label), **28.4%**.
  The best-worst difference across labels is **0.091** for the Black share —
  the choice of training label alone moves Black representation in the
  highest-risk group by ~9 percentage points.

- **Table 3 (alternative allocation policies, holdout).** Observed program
  enrollment is **22.4%** Black. Sampling within predicted-cost bins at
  observed enrollment rates gives 17.7% Black, while prioritizing predicted
  health within the same cost bins raises that to 30.8%. Ranking purely by
  highest predicted cost yields **21.8%** Black; ranking by worst predicted
  health yields **36.7%** Black. A need-based target nearly doubles the share
  of Black patients reached relative to the cost-based ranking.

- **Model fit (holdout R2).** The commercial risk score explains health
  (gagne chronic-condition count) about as well as it explains cost
  (R2 = 0.312 vs 0.118 for log cost on risk score), and a model trained
  directly on health predicts health far better (R2 = 0.733). Predicting need
  is not intrinsically harder than predicting cost; the under-selection of
  Black patients comes from the label, not from model quality.

## Why cost diverges from need

The label "future cost" is generated by the health care system, not by biology
alone. If two patients are equally sick but one faces barriers to care —
access, affordability, trust, referral patterns — that patient consumes fewer
services and accrues lower costs. A model trained to predict cost learns those
utilization patterns and reads "less treated" as "less sick." Because Black
patients in the data generate less cost than White patients at the same level
of measured illness, the cost-trained ranking systematically places equally
sick Black patients lower.

## Why the diagnosis matters — and why retraining alone is not the fix

Nothing is "broken" in the statistical sense: the cost model predicts cost
about as well as this feature set allows. The bias enters through the choice
of prediction target, upstream of any training. Simply retraining the same
pipeline — more data, better features, race excluded from inputs — will
reproduce the same allocation, because the label itself encodes unequal access
to care. Race was already excluded from the model's features here; the
disparity persists because prior cost and utilization features act as proxies.
The actionable lever is the label, not the optimizer.

## Recommendation

Use a **need-based label** (e.g., active chronic conditions / predicted
health) as the allocation target rather than predicted cost. In this synthetic
replication, doing so would raise Black representation among top-ranked
patients from roughly 19–22% to roughly 28–37% (Table 2 / Table 3), much
closer to what illness burden justifies, while — per Table 3 — also
concentrating more avoidable cost and more chronic illness in the enrolled
group. Any deployment should pair this with monitoring of enrollment
composition by race and with community review of what "need" should mean.

## Provenance and caveats

All figures above come from this run's outputs on the public **synthetic**
dataset released with the paper (`results/model_r2.csv`,
`results/table2_concentration_metric.csv`, `results/figure1b.csv`,
`results/table3.csv`). The synthetic data were generated to mimic distributions
in the original private claims data but do not reproduce the paper's exact
private-data values (e.g., the paper's Figure 1b reports a move from 17.7% to
46.5% Black at the 97th percentile; a later correction revises related
figures). Those private-data numbers are quoted only for context and are not
the results of this audit. Because the synthetic data are simulated, effect
sizes here should be read as qualitative confirmation of the cost-versus-need
mechanism, not as estimates for any real population.
"""
