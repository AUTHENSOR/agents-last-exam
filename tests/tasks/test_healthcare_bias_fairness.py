@pytest.mark.parametrize(
    "filename", [name for name in scorer.REQUIRED_OUTPUT_FILES if name.endswith(".csv")]
)
def test_each_numeric_table_remains_strict(reference, candidate, filename):
    rows = list(csv.reader(io.StringIO(candidate[filename])))
    for column, value in enumerate(rows[1]):
        try:
            number = float(value)
        except ValueError:
            continue
        rows[1][column] = repr(number + 0.01)
        break
    else:
        pytest.fail(f"No numeric field in {filename}")
    stream = io.StringIO()
    csv.writer(stream).writerows(rows)
    candidate[filename] = stream.getvalue()
    result = scorer.score_output_bundle(candidate_files=candidate, reference_files=reference)
    assert result.score == 0.0
    assert result.reason == f"{filename}: value_mismatch"


